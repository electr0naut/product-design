// Real-browser check of the order story (FXL-15): node check15.mjs <log> <out.png> <http url>
import fs from 'node:fs';
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const [log, out, url] = process.argv.slice(2);
const origin = new URL(url).origin;
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 2 });
const problems = [], requests = [];
page.on('request', r => requests.push(r.url()));
page.on('console', m => { if (m.type() === 'error') problems.push('console error: ' + m.text()); });
page.on('pageerror', e => problems.push('page error: ' + e.message));
page.on('dialog', d => { problems.push('dialog: ' + d.message()); d.dismiss(); });
await page.goto(url);
await page.fill('#paste', fs.readFileSync(log, 'utf8'));
await page.click('#decode-button');
const count = async () => ({ events: await page.locator('#timeline li.event').count(), cards: await page.locator('#decode article.card').count(), stats: await page.locator('#summary .stat').allTextContents() });
const all = await count();
const links = await page.locator('button.order-link').allTextContents();
const noneButtons = links.filter(t => /NONE/.test(t));
await page.locator('#timeline button.order-link', { hasText: 'ClOrdID C1' }).first().click();
const story = await count();
const banner = (await page.locator('#summary').innerText()).replace(/\s+/g, ' ').slice(0, 400);
await page.screenshot({ path: out });
await page.locator('button.show-all').click();
const back = await count();
await page.locator('#timeline button.order-link', { hasText: 'ClOrdID C9' }).first().click();
const other = await count();
await page.click('#decode-button');
const again = await count();
const r = { all, distinctLinks: [...new Set(links)], story, banner, back, other, again, imgs: await page.locator('img').count(), foreign: requests.filter(u => !u.startsWith(origin)) };
if (noneButtons.length) problems.push('OrderID NONE is a button');
if (!(story.cards < all.cards && story.cards > 0)) problems.push('selecting an order did not narrow the cards');
if (back.cards !== all.cards || again.cards !== all.cards) problems.push('show all or Decode did not restore the whole log');
if (r.imgs) problems.push('an <img> was created');
if (r.foreign.length) problems.push('foreign requests');
console.log(JSON.stringify({ ...r, problems }, null, 1));
await browser.close();
process.exit(problems.length ? 1 : 0);
